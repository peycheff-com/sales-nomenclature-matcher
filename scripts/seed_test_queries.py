# ===================================================================


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate test queries for golden set")
    parser.add_argument(
        "--output",
        "-o",
        type=str,
        default=str(OUTPUT_DEFAULT),
        help=f"Output JSON file (default: {OUTPUT_DEFAULT})",
    )
    parser.add_argument("--count", type=int, default=0, help="Limit query count (0=all)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    queries = _build_queries(rng)

    if args.count > 0:
        queries = queries[: args.count]

    # Stats
    from collections import Counter

    difficulties = Counter(q["difficulty"] for q in queries)
    categories = Counter(q["category"] for q in queries)

    print(f"Generated {len(queries)} test queries")
    print("\nDifficulty breakdown:")
    for d in ["easy", "medium", "hard"]:
        print(f"  {d}: {difficulties.get(d, 0)}")
    print("\nCategory breakdown:")
    for cat, cnt in categories.most_common():
        print(f"  {cat}: {cnt}")

    # Write output
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(
            {
                "version": "1.0",
                "description": "Golden set of client-style product queries for matching evaluation",
                "total_queries": len(queries),
                "difficulty_counts": dict(difficulties),
                "queries": queries,
            },
            f,
            ensure_ascii=False,
            indent=2,
        )

    print(f"\nWritten to {output_path}")


if __name__ == "__main__":
    main()

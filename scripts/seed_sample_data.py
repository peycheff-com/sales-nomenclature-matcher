def _generate_pumps(rng: random.Random) -> list[dict]:
    products = []
    for brand, model_pref, ptype, variants in PUMP_PRODUCTS:
        for suffix, power, flow, head in variants:
            model = f"{model_pref} {suffix}"
            name = f"Насос {ptype} {brand} {model}"
            full_name = f"Насос {ptype} {brand} {model} {power} Вт Q={flow} м³/ч H={head} м"
            code = (
                f"PM-{brand[:3].upper()}-{model_pref}-{suffix.replace(' ', '').replace('/', '-')}"
            )
            article = f"{model_pref}{suffix.replace(' ', '').replace('/', '')}"
            mfr_code = f"{brand[:4].upper()}-{rng.randint(10000, 99999)}"

            products.append(
                _make_product(
                    code=code,
                    article=article,
                    name=name,
                    full_name=full_name,
                    brand=brand,
                    manufacturer=brand,
                    manufacturer_code=mfr_code,
                    category="pumps",
                    unit="шт",
                    weight_value=Decimal(str(round(power * 0.02 + rng.uniform(0.5, 3.0), 2))),
                    weight_unit="кг",
                    attributes={"power_w": power, "flow_m3h": flow, "head_m": head},
                )
            )
    return products



def _generate_fasteners(rng: random.Random) -> list[dict]:
    products = []
    for name_tpl, code_pref, sizes, unit, brands in FASTENER_TEMPLATES:
        for size_tuple in sizes:
            s = size_tuple[0]
            length = size_tuple[1] if len(size_tuple) > 1 else None
            name = name_tpl.format(s=s, l=length) if length else name_tpl.format(s=s, l="")
            name = name.strip()

            # Generate per-brand, per-packaging variants
            for brand in brands:
                packs = [1, rng.choice([10, 25, 50]), rng.choice([100, 200, 500, 1000])]
                for pack in packs:
                    pack_str = f"уп. {pack} шт" if pack > 1 else ""
                    fname = f"{name} {brand}"
                    if pack > 1:
                        fname += f" (упаковка {pack} шт)"

                    size_str = f"{s}x{length}" if length else str(s)
                    code = (
                        f"KR-{code_pref}-{size_str}-{brand[:2].upper()}-{pack}"
                        if pack > 1
                        else f"KR-{code_pref}-{size_str}-{brand[:2].upper()}"
                    )
                    article = (
                        f"{code_pref}{size_str.replace('x', '')}P{pack}{brand[:2].upper()}"
                        if pack > 1
                        else f"{code_pref}{size_str.replace('x', '')}{brand[:2].upper()}"
                    )
                    mfr_code = f"{brand[:3].upper()}-{code_pref}-{size_str}"

                    products.append(
                        _make_product(
                            code=code,
                            article=article,
                            name=name + (f" {brand} уп.{pack}шт" if pack > 1 else f" {brand}"),
                            full_name=fname,
                            brand=brand,
                            manufacturer=brand,
                            manufacturer_code=mfr_code,
                            category="fasteners",
                            unit=unit,
                            size_value=Decimal(str(s)),
                            size_unit="мм",
                            weight_value=Decimal(str(round(s * 0.3 * pack * 0.001, 3)))
                            if length
                            else None,
                            weight_unit="кг",
                            packaging=pack_str if pack > 1 else None,
                        )
                    )
    return products



def _generate_electrical(rng: random.Random) -> list[dict]:
    products = []

    # Circuit breakers, RCDs, RCBOs
    for brand, line, dev_type, variants in ELECTRICAL_PRODUCTS:
        for params in variants:
            if "автомат" in dev_type:
                amps, char = params
                name = f"{dev_type} {brand} {line} {char}{amps}А"
                full_name = f"Автоматический выключатель {brand} {line} {char}{amps}А 4.5кА"
                article = f"{line.replace(' ', '')}{char}{amps}"
                code = f"EL-{brand[:3].upper()}-{line.replace(' ', '')}-{char}{amps}"
                mfr_code = f"2CDS2{rng.randint(10, 99)}0001R0{rng.randint(100, 999)}"
            elif "УЗО" in dev_type:
                amps, ma = params
                name = f"{dev_type} {brand} {line} {amps}А {ma}мА"
                full_name = f"Устройство защитного отключения {brand} {line} {amps}А {ma}мА тип AC"
                article = f"{line.replace(' ', '')}UZO{amps}A{ma}"
                code = f"EL-{brand[:3].upper()}-{line.replace(' ', '')}-UZO{amps}-{ma}"
                mfr_code = f"2CSF2{rng.randint(10, 99)}0R1{rng.randint(100, 999)}"
            else:
                amps, ma = params
                name = f"{dev_type} {brand} {line} C{amps}А {ma}мА"
                full_name = f"Дифференциальный автомат {brand} {line} C{amps}А {ma}мА тип AC"
                article = f"{line.replace(' ', '')}DIF{amps}A{ma}"
                code = f"EL-{brand[:3].upper()}-{line.replace(' ', '')}-DIF{amps}-{ma}"
                mfr_code = f"2CSR2{rng.randint(10, 99)}0R1{rng.randint(100, 999)}"

            products.append(
                _make_product(
                    code=code,
                    article=article,
                    name=name,
                    full_name=full_name,
                    brand=brand,
                    manufacturer=brand,
                    manufacturer_code=mfr_code,
                    category="electrical",
                    unit="шт",
                )
            )

    # Wiring accessories
    for brand, line, items in WIRING_ACCESSORIES:
        for type_name, colors in items:
            for color in colors:
                name = f"{type_name} {brand} {line} {color}"
                full_name = f"{type_name} {brand} серия {line} {color} скрытой установки"
                line_ns = line.replace(' ', '')
                tn3 = type_name[:3].upper()
                brd3 = brand[:3].upper()
                article = (
                    f"{line_ns}-{tn3}"
                    f"-{color[:2].upper()}"
                    f"-{rng.randint(100, 999)}"
                )
                code = (
                    f"EL-{brd3}-{line_ns}"
                    f"-{tn3}-{color[:3].upper()}"
                )
                mfr_code = f"{brand[:3].upper()}{rng.randint(100000, 999999)}"

                products.append(
                    _make_product(
                        code=code,
                        article=article,
                        name=name,
                        full_name=full_name,
                        brand=brand,
                        manufacturer=brand,
                        manufacturer_code=mfr_code,
                        category="electrical",
                        unit="шт",
                    )
                )

    # Electrical extras: cable trays, conduits, junction boxes
    for prod_type, size_list in ELECTRICAL_EXTRAS:
        for brand in CABLE_TRAY_BRANDS:
            for dims in size_list:
                w, h, lengths = dims
                for length in lengths:
                    if prod_type == "Кабель-канал":
                        name = f"Кабель-канал {w}x{h} мм {length} м {brand}"
                        full_name = f"Кабель-канал {w}x{h} мм L={length} м {brand} белый ПВХ"
                        code = f"EL-KK-{w}x{h}-{length}M-{brand[:3].upper()}"
                        article = f"KK{w}x{h}L{length}{brand[:2].upper()}"
                        unit = "шт"
                        sz = Decimal(str(w))
                    elif prod_type == "Труба гофрированная ПВХ":
                        name = f"Труба гофр. ПВХ d{w} мм {length} м {brand}"
                        full_name = (
                            f"Труба гофрированная ПВХ d{w}/{h} мм бухта {length} м {brand} серая"
                        )
                        code = f"EL-TG-{w}-{length}M-{brand[:3].upper()}"
                        article = f"TG{w}B{length}{brand[:2].upper()}"
                        unit = "м"
                        sz = Decimal(str(w))
                    else:
                        name = f"Коробка распред. {w}x{h}x{length} мм {brand}"
                        full_name = f"Коробка распределительная {w}x{h}x{length} мм {brand} IP55"
                        code = f"EL-KR-{w}x{h}x{length}-{brand[:3].upper()}"
                        article = f"KR{w}{h}{length}{brand[:2].upper()}"
                        unit = "шт"
                        sz = Decimal(str(w))

                    mfr_code = f"{brand[:3].upper()}-{rng.randint(10000, 99999)}"
                    products.append(
                        _make_product(
                            code=code,
                            article=article,
                            name=name,
                            full_name=full_name,
                            brand=brand,
                            manufacturer=brand,
                            manufacturer_code=mfr_code,
                            category="electrical",
                            unit=unit,
                            size_value=sz,
                            size_unit="мм",
                        )
                    )

    # DIN rail accessories: contactors, timers, SPDs, busbars, enclosures
    for brand, dev_type, variants in ELECTRICAL_DIN_EXTRAS:
        for name_suffix, article_code in variants:
            name = f"{dev_type.capitalize()} {brand} {name_suffix}"
            full_name = f"{dev_type.capitalize()} {brand} {name_suffix} DIN-рейка"
            code = f"EL-{brand[:3].upper()}-DIN-{article_code[:10]}"
            mfr_code = article_code

            products.append(
                _make_product(
                    code=code,
                    article=article_code,
                    name=name,
                    full_name=full_name,
                    brand=brand,
                    manufacturer=brand,
                    manufacturer_code=mfr_code,
                    category="electrical",
                    unit="шт",
                )
            )

    return products



CABLE_COLORS: dict[str, list[str]] = {
    "ВВГнг(А)-LS": ["чёрный"],
    "ВВГнг(А)": ["чёрный"],
    "ПВС": ["белый", "чёрный"],
    "NYM": ["серый"],
    "ШВВП": ["белый", "чёрный"],
    "КГ": ["чёрный"],
    "СИП-4": ["чёрный"],
    "АВВГ": ["чёрный"],
}


def _generate_cables(rng: random.Random) -> list[dict]:
    products = []
    for ctype, gost, cores_list, sections, lengths, fire_rating in CABLE_TYPES:
        colors = CABLE_COLORS.get(ctype, [""])
        for cores in cores_list:
            for section in sections:
                for length in lengths:
                    # All brands for each cable variant
                    brands_subset = CABLE_BRANDS
                    for brand in brands_subset:
                        for color in colors:
                            sec_str = str(section).rstrip("0").rstrip(".")
                            color_part = f" {color}" if color else ""
                            name = f"Кабель {ctype} {cores}х{sec_str}{color_part} {brand}"
                            full_name = (
                                f"Кабель силовой {ctype} {cores}x{sec_str} мм²{color_part} "
                                f"{gost} {brand} бухта {length} м"
                            )
                            ctype_short = ctype.split('(')[0].split('-')[0]
                            brd3 = brand[:3].upper()
                            clr2 = color[:2].upper() if color else 'DF'
                            code = (
                                f"CB-{ctype_short}-{cores}x{sec_str}"
                                f"-{brd3}-{length}-{clr2}"
                            )
                            ctype_clean = ctype.replace(
                                '(', ''
                            ).replace(')', '').replace('-', '')
                            brd2 = brand[:2].upper()
                            clr1 = (
                                color[:1].upper() if color else ''
                            )
                            article = (
                                f"{ctype_clean}{cores}x{sec_str}"
                                f"{brd2}{clr1}"
                            )
                            mfr_code = (
                                f"{brand[:3].upper()}-{cores}x{sec_str}-{rng.randint(100, 999)}"
                            )
                            weight = round(cores * section * length * 0.012, 2)

                            products.append(
                                _make_product(
                                    code=code,
                                    article=article,
                                    name=name,
                                    full_name=full_name,
                                    brand=brand,
                                    manufacturer=brand,
                                    manufacturer_code=mfr_code,
                                    category="cables",
                                    unit="м",
                                    size_value=Decimal(str(section)),
                                    size_unit="мм²",
                                    weight_value=Decimal(str(weight)),
                                    weight_unit="кг",
                                    packaging=f"бухта {length} м",
                                )
                            )
    return products



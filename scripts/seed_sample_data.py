PN_CLASSES_PP = [10, 16, 20, 25]  # For PPR/PVC only
WALL_THICKNESS = {
    10: 0.05,
    16: 0.065,
    20: 0.08,
    25: 0.10,
}


def _generate_pipes(rng: random.Random) -> list[dict]:
    products = []
    for pipe_abbr, pipe_full, material, code_pref, diameters, lengths, brands in PIPE_TYPES:
        # PP and PVC pipes get PN class variants; others get single variant
        is_polymer = code_pref in ("PP", "PVC")
        pn_list = PN_CLASSES_PP if is_polymer else [0]

        for d in diameters:
            for length in lengths:
                for brand in brands:
                    for pn in pn_list:
                        wall_ratio = WALL_THICKNESS.get(pn, 0.07)
                        wall = round(d * wall_ratio, 1)
                        sdr = ""
                        if pn == 10:
                            sdr = "SDR17"
                        elif pn == 16:
                            sdr = "SDR11"
                        elif pn == 20:
                            sdr = "SDR9"
                        elif pn == 25:
                            sdr = "SDR7.4"
                        sdr_part = f" {sdr}" if sdr else ""
                        pn_part = f" PN{pn}" if pn else ""

                        name = f"Труба {pipe_abbr} {d} мм{pn_part} {length} м {brand}"
                        full_name = (
                            f"Труба {pipe_full} {brand} d{d}x{wall} мм"
                            f" L={length} м{sdr_part}{pn_part}"
                        )
                        len_s = str(length).replace('.', '')
                        brd = brand[:3].upper()
                        if pn:
                            code = (
                                f"TR-{code_pref}-{d}"
                                f"-PN{pn}-{len_s}-{brd}"
                            )
                        else:
                            code = (
                                f"TR-{code_pref}-{d}"
                                f"-{len_s}-{brd}"
                            )
                        article = (
                            f"{code_pref}{d}PN{pn}{brand[:2].upper()}"
                            if pn
                            else f"{code_pref}{d}{str(wall).replace('.', '')}{brand[:2].upper()}"
                        )
                        unit = "м" if length >= 10 else "шт"
                        mfr_code = f"{brand[:3].upper()}-{code_pref}{d}-{rng.randint(100, 999)}"

                        products.append(
                            _make_product(
                                code=code,
                                article=article,
                                name=name,
                                full_name=full_name,
                                brand=brand,
                                manufacturer=brand,
                                manufacturer_code=mfr_code,
                                category="pipes",
                                unit=unit,
                                size_value=Decimal(str(d)),
                                size_unit="мм",
                                weight_value=Decimal(str(round(d * length * 0.015, 2))),
                                weight_unit="кг",
                            )
                        )

        # Fittings for this pipe type — per brand
        for fit_name, fit_code in FITTING_TYPES:
            for d in diameters:
                for brand in brands:
                    name = f"{fit_name} {pipe_abbr} {d} мм {brand}"
                    full_name = f"{fit_name} {pipe_full} {brand} d{d} мм {material}"
                    code = f"FT-{code_pref}-{fit_code}-{d}-{brand[:3].upper()}"
                    article = f"{code_pref}{fit_code}{d}{brand[:2].upper()}"
                    mfr_code = f"{brand[:3].upper()}-{fit_code}{d}"

                    products.append(
                        _make_product(
                            code=code,
                            article=article,
                            name=name,
                            full_name=full_name,
                            brand=brand,
                            manufacturer=brand,
                            manufacturer_code=mfr_code,
                            category="pipes",
                            unit="шт",
                            size_value=Decimal(str(d)),
                            size_unit="мм",
                        )
                    )
    return products



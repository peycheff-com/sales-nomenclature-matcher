_ONEC_COUNTER = 0


def _make_product(
    *,
    code: str,
    article: str,
    name: str,
    full_name: str,
    brand: str,
    manufacturer: str,
    manufacturer_code: str,
    category: str,
    unit: str,
    size_value: Decimal | None = None,
    size_unit: str | None = None,
    weight_value: Decimal | None = None,
    weight_unit: str | None = None,
    volume_value: Decimal | None = None,
    volume_unit: str | None = None,
    packaging: str | None = None,
    attributes: dict | None = None,
) -> dict:
    global _ONEC_COUNTER
    _ONEC_COUNTER += 1

    cat_id, cat_path = CATEGORIES[category]

    # Deterministic UUID from code
    product_id = str(uuid.uuid5(uuid.NAMESPACE_DNS, f"sample.{code}"))
    onec_ref = f"{_ONEC_COUNTER:09d}"

    # Normalized brand
    normalized_brand = brand.lower().strip()

    # Normalized name
    normalized_name = name.lower().strip()

    # Search document
    search_parts = [name]
    if full_name:
        search_parts.append(full_name)
    if brand:
        search_parts.append(brand)
    if article:
        search_parts.append(article)
    if manufacturer:
        search_parts.append(manufacturer)
    if manufacturer_code:
        search_parts.append(manufacturer_code)
    search_parts.append(cat_path)
    search_document = " | ".join(search_parts)

    # Source hash
    hash_input = json.dumps(
        {
            "name": name,
            "article": article,
            "brand": brand,
            "code": code,
        },
        sort_keys=True,
        ensure_ascii=False,
    )
    source_hash = hashlib.sha256(hash_input.encode()).hexdigest()[:16]

    return {
        "product_id": product_id,
        "onec_ref": onec_ref,
        "code": code,
        "article": article,
        "name": name,
        "full_name": full_name,
        "normalized_name": normalized_name,
        "normalized_full_name": full_name.lower().strip() if full_name else None,
        "brand": brand,
        "normalized_brand": normalized_brand,
        "manufacturer": manufacturer,
        "manufacturer_code": manufacturer_code,
        "category_id": cat_id,
        "category_path": cat_path,
        "unit": unit,
        "packaging": packaging,
        "size_value": size_value,
        "size_unit": size_unit,
        "weight_value": weight_value,
        "weight_unit": weight_unit,
        "volume_value": volume_value,
        "volume_unit": volume_unit,
        "attributes_json": attributes or {},
        "search_document": search_document,
        "is_active": True,
        "source_hash": source_hash,
    }



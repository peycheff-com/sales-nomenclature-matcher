def _generate_tools(rng: random.Random) -> list[dict]:
    products = []
    all_tools = TOOL_PRODUCTS + SAW_PRODUCTS
    for brand, model, ttype, name_ru, power, weight, extras in all_tools:
        full_name = name_ru
        if extras:
            parts = [name_ru]
            for k, v in extras.items():
                if k == "chuck":
                    parts.append(f"патрон {v}")
                elif k == "energy_j":
                    parts.append(f"энергия удара {v} Дж")
                elif k == "disc_mm":
                    parts.append(f"диск {v} мм")
            full_name = " ".join(parts)

        name_short = (
            f"{ttype.capitalize()} {brand} {model}"
            if power
            else f"{ttype.capitalize()} акк. {brand} {model}"
        )
        code = f"TL-{brand[:3].upper()}-{model.replace(' ', '-').replace('/', '-')}"
        article = model.replace(" ", "").replace("/", "")
        mfr_code = f"{brand[:4].upper()}-{model.replace(' ', '')}"

        products.append(
            _make_product(
                code=code,
                article=article,
                name=name_short,
                full_name=full_name,
                brand=brand,
                manufacturer=brand,
                manufacturer_code=mfr_code,
                category="tools",
                unit="шт",
                weight_value=Decimal(str(weight)),
                weight_unit="кг",
                attributes=extras,
            )
        )

    # Drill bits / consumables
    for brand, cons_type, sizes in TOOL_CONSUMABLES:
        for d_mm, l_total, l_work in sizes:
            name = f"Бур {cons_type.split()[-1]} {brand} {d_mm}x{l_total} мм"
            full_name = (
                f"{cons_type.capitalize()} {brand} {d_mm}x{l_total} мм (раб. часть {l_work} мм)"
            )
            code = f"TL-BUR-{brand[:3].upper()}-{d_mm}x{l_total}"
            article = f"BUR{brand[:2].upper()}{d_mm}x{l_total}"
            mfr_code = f"{brand[:4].upper()}-BUR-{d_mm}-{l_total}"

            products.append(
                _make_product(
                    code=code,
                    article=article,
                    name=name,
                    full_name=full_name,
                    brand=brand,
                    manufacturer=brand,
                    manufacturer_code=mfr_code,
                    category="tools",
                    unit="шт",
                    size_value=Decimal(str(d_mm)),
                    size_unit="мм",
                )
            )

    # Cutting / grinding discs
    for brand, disc_type, diameters, thicknesses in DISC_CONSUMABLES:
        for dia in diameters:
            for thick in thicknesses:
                bore = 22 if dia <= 180 else 22
                name = f"Круг {disc_type} {brand} {dia}x{thick}x{bore}"
                full_name = f"Круг {disc_type} {brand} {dia}x{thick}x{bore} мм"
                code = f"TL-DSK-{brand[:3].upper()}-{disc_type[:3].upper()}-{dia}x{thick}"
                article = f"DSK{brand[:2].upper()}{dia}x{str(thick).replace('.', '')}"
                mfr_code = f"{brand[:4].upper()}-DSK-{dia}-{thick}"

                products.append(
                    _make_product(
                        code=code,
                        article=article,
                        name=name,
                        full_name=full_name,
                        brand=brand,
                        manufacturer=brand,
                        manufacturer_code=mfr_code,
                        category="tools",
                        unit="шт",
                        size_value=Decimal(str(dia)),
                        size_unit="мм",
                    )
                )

    return products



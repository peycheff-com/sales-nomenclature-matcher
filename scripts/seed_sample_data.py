def _generate_plumbing(rng: random.Random) -> list[dict]:
    products = []
    for brand, line, ptype, variants in PLUMBING_PRODUCTS:
        for article_code, desc, _price in variants:
            name = f"{ptype.capitalize()} {brand} {line} {desc}"
            full_name = f"{ptype.capitalize()} {brand} {line} {article_code} {desc}"
            code = f"SN-{brand[:3].upper()}-{article_code}"
            mfr_code = article_code
            weight = round(rng.uniform(0.3, 15.0), 2)

            products.append(
                _make_product(
                    code=code,
                    article=article_code,
                    name=name,
                    full_name=full_name,
                    brand=brand,
                    manufacturer=brand,
                    manufacturer_code=mfr_code,
                    category="plumbing",
                    unit="шт",
                    weight_value=Decimal(str(weight)),
                    weight_unit="кг",
                )
            )
    return products



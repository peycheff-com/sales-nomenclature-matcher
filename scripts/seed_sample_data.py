def _generate_paints(rng: random.Random) -> list[dict]:
    products = []
    for brand, line, ptype, colors, volumes, coverage in PAINT_PRODUCTS:
        for color in colors:
            for vol in volumes:
                name = f"Краска {ptype} {brand} {line} {color} {vol} л"
                full_name = f"Краска {ptype} {brand} {line} {color} {vol} л расход {coverage} м²/л"
                code = f"KR-{brand[:3].upper()}-{line[:3].upper()}-{color[:2].upper()}-{vol}"
                article = f"{brand[:3].upper()}{line.replace(' ', '')[:5]}{vol}L"
                mfr_code = f"{brand[:4].upper()}-{rng.randint(10000, 99999)}"

                products.append(
                    _make_product(
                        code=code,
                        article=article,
                        name=name,
                        full_name=full_name,
                        brand=brand,
                        manufacturer=brand,
                        manufacturer_code=mfr_code,
                        category="paints",
                        unit="шт",
                        volume_value=Decimal(str(vol)),
                        volume_unit="л",
                        weight_value=Decimal(str(round(vol * 1.35, 2))),
                        weight_unit="кг",
                        packaging=f"банка {vol} л" if vol <= 3 else f"ведро {vol} л",
                    )
                )

    for brand, line, ltype, finishes, volumes in LACQUER_PRODUCTS:
        for finish in finishes:
            for vol in volumes:
                name = f"Лак {ltype} {brand} {line} {finish} {vol} л"
                full_name = f"Лак {ltype} {brand} {line} {finish} {vol} л"
                code = f"LK-{brand[:3].upper()}-{line[:3].upper()}-{finish[:3].upper()}-{vol}"
                article = f"LK{brand[:3].upper()}{finish[:2].upper()}{vol}L"
                mfr_code = f"{brand[:4].upper()}-LK-{rng.randint(1000, 9999)}"

                products.append(
                    _make_product(
                        code=code,
                        article=article,
                        name=name,
                        full_name=full_name,
                        brand=brand,
                        manufacturer=brand,
                        manufacturer_code=mfr_code,
                        category="paints",
                        unit="шт",
                        volume_value=Decimal(str(vol)),
                        volume_unit="л",
                        weight_value=Decimal(str(round(vol * 1.1, 2))),
                        weight_unit="кг",
                        packaging=f"банка {vol} л",
                    )
                )

    # Primers
    for brand, prod_name, primer_type, volumes, coverage in PRIMER_PRODUCTS:
        for vol in volumes:
            name = f"Грунтовка {primer_type} {brand} {prod_name} {vol} л"
            full_name = (
                f"Грунтовка {primer_type} {brand} {prod_name} {vol} л расход {coverage} м²/л"
            )
            code = f"GR-{brand[:3].upper()}-{prod_name[:3].upper()}-{vol}"
            article = f"GR{brand[:3].upper()}{prod_name.replace(' ', '')[:5]}{vol}L"
            mfr_code = f"{brand[:4].upper()}-GR-{rng.randint(1000, 9999)}"

            products.append(
                _make_product(
                    code=code,
                    article=article,
                    name=name,
                    full_name=full_name,
                    brand=brand,
                    manufacturer=brand,
                    manufacturer_code=mfr_code,
                    category="paints",
                    unit="шт",
                    volume_value=Decimal(str(vol)),
                    volume_unit="л",
                    weight_value=Decimal(str(round(vol * 1.05, 2))),
                    weight_unit="кг",
                    packaging=f"канистра {vol} л" if vol >= 5 else f"банка {vol} л",
                )
            )

    # Specialty: sealants, foams, adhesives
    for brand, prod_name, ptype, volumes, vunit in SPECIALTY_PRODUCTS:
        colors = SPECIALTY_COLORS.get(ptype, [""])
        for vol in volumes:
            for color in colors:
                color_part = f" {color}" if color else ""
                name = f"{ptype.capitalize()} {brand} {prod_name}{color_part} {vol} л"
                full_name = f"{ptype.capitalize()} {brand} {prod_name}{color_part} {vol} л"
                brd3 = brand[:3].upper()
                pn5 = prod_name[:5].replace(' ', '').upper()
                clr3 = color[:3].upper() if color else 'STD'
                code = f"SP-{brd3}-{pn5}-{clr3}-{vol}"
                article = f"SP{brand[:3].upper()}{ptype[:3].upper()}{vol}L"
                mfr_code = f"{brand[:4].upper()}-SP-{rng.randint(1000, 9999)}"

                products.append(
                    _make_product(
                        code=code,
                        article=article,
                        name=name,
                        full_name=full_name,
                        brand=brand,
                        manufacturer=brand,
                        manufacturer_code=mfr_code,
                        category="paints",
                        unit="шт",
                        volume_value=Decimal(str(vol)),
                        volume_unit="л",
                        weight_value=Decimal(str(round(vol * 1.2, 2))),
                        weight_unit="кг",
                    )
                )

    return products



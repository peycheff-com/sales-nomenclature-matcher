def _generate_insulation(rng: random.Random) -> list[dict]:
    products = []
    for brand, line, material, thicknesses, size_lxw, densities, unit in INSULATION_PRODUCTS:
        for thick in thicknesses:
            for density in densities:
                name = f"Утеплитель {brand} {line} {thick} мм плотн.{density}"
                full_name = (
                    f"Утеплитель {material} {brand} {line} "
                    f"{size_lxw}x{thick} мм плотность {density} кг/м³"
                )
                code = f"INS-{brand[:3].upper()}-{line[:3].upper()}-{thick}-D{density}"
                article = f"{brand[:3].upper()}{line.replace(' ', '')[:6]}{thick}D{density}"
                mfr_code = f"{brand[:4].upper()}-{thick}-{density}-{rng.randint(10, 99)}"
                # Parse dimensions for weight estimate
                dims = size_lxw.split("x")
                area_m2 = int(dims[0]) / 1000 * int(dims[1]) / 1000
                weight = round(
                    area_m2 * (thick / 1000) * density * rng.choice([4, 6, 8, 10, 12]), 2
                )

                products.append(
                    _make_product(
                        code=code,
                        article=article,
                        name=name,
                        full_name=full_name,
                        brand=brand,
                        manufacturer=brand,
                        manufacturer_code=mfr_code,
                        category="insulation",
                        unit=unit,
                        size_value=Decimal(str(thick)),
                        size_unit="мм",
                        weight_value=Decimal(str(weight)),
                        weight_unit="кг",
                        packaging=unit,
                    )
                )
    return products



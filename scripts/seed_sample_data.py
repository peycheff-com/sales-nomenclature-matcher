async def main() -> None:
    parser = argparse.ArgumentParser(description="Generate and insert sample catalog data")
    parser.add_argument("--dry-run", action="store_true", help="Generate only, don't insert")
    parser.add_argument("--count", type=int, default=0, help="Limit product count (0=all)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility")
    args = parser.parse_args()

    print("Generating sample catalog data...")
    products = generate_products(seed=args.seed)

    if args.count > 0:
        products = products[: args.count]
        print(f"  Trimmed to {len(products)} products")

    # Summary by category
    from collections import Counter

    cats = Counter(p["category_path"] for p in products)
    print("\nCategory breakdown:")
    for cat, cnt in cats.most_common():
        print(f"  {cat}: {cnt}")

    # Summary by brand (top 15)
    brands = Counter(p["brand"] for p in products)
    print(f"\nTop 15 brands (of {len(brands)} total):")
    for brand, cnt in brands.most_common(15):
        print(f"  {brand}: {cnt}")

    if args.dry_run:
        print("\n--dry-run: Skipping database insert.")
        print("\nSample products:")
        for p in products[:10]:
            print(f"  [{p['code']}] {p['name']}")
            print(f"    brand={p['brand']}  article={p['article']}  unit={p['unit']}")
        return

    print(f"\nInserting {len(products)} products into database...")
    await insert_products(products)
    print("\nSeed complete!")


if __name__ == "__main__":
    asyncio.run(main())

UPDATE_TSV_SQL = """\
UPDATE catalog_products
SET search_tsv = to_tsvector('russian', coalesce(search_document, ''))
"""


async def insert_products(products: list[dict], batch_size: int = 500) -> None:
    """Insert products into the database in batches."""
    from sqlalchemy import text
    from sqlalchemy.ext.asyncio import create_async_engine

    from matcher.config import settings

    engine = create_async_engine(settings.async_database_url, echo=False)

    inserted = 0
    async with engine.begin() as conn:
        for i in range(0, len(products), batch_size):
            batch = products[i : i + batch_size]
            for item in batch:
                # Cast attributes_json dict to string for raw SQL
                params = {
                    **item,
                    "attributes_json": json.dumps(item["attributes_json"], ensure_ascii=False),
                }
                # Convert Decimal to float for asyncpg compatibility
                for key in ("size_value", "weight_value", "volume_value"):
                    if params[key] is not None:
                        params[key] = float(params[key])
                await conn.execute(text(INSERT_SQL), params)
            inserted += len(batch)
            print(f"  Inserted {inserted}/{len(products)}...")

        # Update full-text search vectors
        print("  Updating search_tsv vectors...")
        await conn.execute(text(UPDATE_TSV_SQL))

    await engine.dispose()
    print(f"  Done. {inserted} products in database.")


